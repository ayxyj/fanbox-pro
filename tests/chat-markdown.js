'use strict';
const assert = require('assert/strict');
const fs = require('fs');
const vm = require('vm');
const window = { marked: require('../public/vendor/marked/marked.min.js') };
vm.runInNewContext(fs.readFileSync('public/chat-markdown.js', 'utf8'), { window, URL });
const render = window.renderChatMarkdown;
const result = render('## 整体结构\n\n| 目录 | 说明 |\n| --- | --- |\n| `conf/` | **配置** |\n\n- 项目\n\n```sh\necho test\n```'.replaceAll('\\n','\n'));
assert(result.includes('<h2>整体结构</h2>'));
assert(result.includes('<table>'));
assert(result.includes('<strong>配置</strong>'));
assert(result.includes('<code>conf/</code>'));
assert(result.includes('<li>项目</li>'));
assert(result.includes('<pre><code class="language-sh">'));
assert(!render('[危险](javascript:alert%281%29)').includes('href='));
assert(!render('<img src=x onerror=alert(1)>').includes('<img'));
assert(!render('![remote](https://example.com/tracker)').includes('<img'));
assert(render('[链接](https://example.com)').includes('rel="noopener noreferrer"'));
for (const text of ['**部分', '| a | b |\n|--', '```sh\necho']) assert.equal(typeof render(text), 'string');
console.log('PASS: Markdown headings, tables, lists, code, streaming fragments and safe links');
