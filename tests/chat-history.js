'use strict';
const assert = require('assert/strict'), fs = require('fs'), os = require('os'), path = require('path');
const { ChatHistory } = require('../electron/chat-history');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'fanbox-history-'));
(async () => {
  const history = new ChatHistory(directory), target = { key: 'host-a', label: 'Server A' };
  const record = await history.open(target);
  await history.begin(record.id, '检查服务状态');
  history.event(record.id, { id: 'run', type: 'text-delta', text: '检查完成', step: 1 });
  history.event(record.id, { id: 'run', type: 'reasoning-delta', text: '服务返回的分析', step: 1 });
  history.event(record.id, { id: 'run', type: 'command', text: 'systemctl status example' });
  history.event(record.id, { id: 'run', type: 'output', text: 'SECRET_TERMINAL_OUTPUT' });
  await assert.rejects(history.begin(record.id, 'duplicate'), /正在运行/);
  await assert.rejects(history.remove(record.id), /停止/);
  await history.finish(record.id);
  const reloaded = new ChatHistory(directory), restored = await reloaded.open(target);
  assert.equal(restored.id, record.id); assert.equal(restored.title, '检查服务状态');
  assert(restored.items.some(i => i.reasoning === '服务返回的分析'));
  assert(!JSON.stringify(restored).includes('SECRET_TERMINAL_OUTPUT'));
  assert.deepEqual(reloaded.context(restored).map(m => m.role), ['user', 'assistant', 'assistant']);
  assert(JSON.stringify(reloaded.context(restored)).includes('历史命令（完成状态未知'));
  const terminalOne = await reloaded.forSession(target, 'terminal-one');
  const terminalTwo = await reloaded.forSession(target, 'terminal-two');
  assert.notEqual(terminalOne.id, terminalTwo.id, 'same host/shell must not merge terminal conversations');
  assert.equal((await reloaded.forSession(target, 'terminal-one')).id, terminalOne.id, 'same terminal keeps its binding');
  await assert.rejects(reloaded.forSession(target, 'terminal-two', terminalOne.id), /另一终端/);
  reloaded.release('terminal-one');
  assert.equal((await reloaded.forSession(target, 'terminal-two', terminalOne.id)).id, terminalOne.id, 'closed terminal history can be explicitly rebound');
  await reloaded.remove(terminalOne.id); await reloaded.remove(terminalTwo.id);
  await assert.rejects(reloaded.open({ key: 'host-b', label: 'B' }, record.id), /对应/);
  const second = await reloaded.open(target, undefined, true); assert.notEqual(second.id, record.id);
  await reloaded.begin(second.id, '中断测试'); await reloaded.flush();
  const interrupted = new ChatHistory(directory), snapshot = await interrupted.get(second.id);
  assert(!snapshot.running); assert(snapshot.items.some(i => i.kind === 'notice'));
  await interrupted.remove(second.id); assert.equal((await new ChatHistory(directory).list()).length, 1);
  console.log('PASS: restart persistence, separate conversations, target isolation, analysis/command history, no PTY output, safe context restoration, interrupted tasks and deletion.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => fs.rmSync(directory, { recursive: true, force: true }));
