'use strict';
const assert = require('assert/strict'), fs = require('fs'), os = require('os'), path = require('path');
const { RemoteStore } = require('../electron/remote-store');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'fanbox-shortcuts-'));
const store = new RemoteStore(root, {});
const a = store.save({ host: 'test-a', username: 'tester' });
const b = store.save({ host: 'test-b', username: 'tester' });
const id = store.saveShortcut({ profileId: a, name: 'Read logs', group: 'Ops', command: 'pwd\r\nls -l' });
assert.equal(store.shortcuts(a)[0].command, 'pwd\nls -l');
assert.equal(store.shortcuts(b).length, 0);
assert.throws(() => store.saveShortcut({ profileId: b, id, name: 'cross-profile', command: 'pwd' }), /不存在/);
assert.throws(() => store.saveShortcut({ profileId: a, name: 'control', command: '\x03' }), /控制字符/);
store.save({ ...store.list().find(p => p.id === a), name: 'Edited profile' });
assert.equal(store.shortcuts(a)[0].id, id, 'editing SSH must retain shortcuts');
assert.equal(store.get(a).terminalType, 'xterm');
store.renameShortcutGroup({ profileId: a, group: 'Ops', name: 'Daily' });
assert.equal(new RemoteStore(root, {}).shortcuts(a)[0].group, 'Daily');
store.renameShortcutGroup({ profileId: a, group: 'Daily', name: '' });
assert.equal(store.shortcuts(a)[0].group, '');
const before = JSON.stringify(store.shortcuts(a)), persist = store.persist;
store.persist = () => { throw Error('disk full'); };
assert.throws(() => store.deleteShortcut({ profileId: a, id }), /disk full/);
assert.equal(JSON.stringify(store.shortcuts(a)), before);
store.persist = persist;
store.deleteShortcut({ profileId: a, id });
assert.equal(new RemoteStore(root, {}).shortcuts(a).length, 0);
console.log('PASS: shortcut persistence, multiline, profile isolation, group rename/removal, profile edit retention, rollback');
