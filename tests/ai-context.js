'use strict';
const assert = require('assert/strict');
const { retainContext } = require('../electron/ai-context');
let mode = 'initial', count = 0, captured;
require('../electron/model-api').requestModel = async (_config, messages) => {
  captured = messages;
  if (mode === 'failure') throw Error('fixture timeout');
  if (mode === 'steps') return { role: 'assistant', content: '', tool_calls: [{ id: 'step' + (++count), type: 'function', function: { name: 'execute_command', arguments: JSON.stringify({ command: 'inspect-' + count }) } }] };
  return { role: 'assistant', content: 'latest answer' };
};
require('../electron/terminal-command').terminalCommand = async () => ({ completed: true, code: 0, output: 'LATEST_RESULT_' + count });
const { ShellAI } = require('../electron/shell-ai');
const identity = {}, config = { model: 'fixture', baseUrl: 'http://fixture', mode: 'auto', interactive: true };
const ai = new ShellAI({ store: { aiConfig: () => config }, target: () => ({ identity, environment: { host: 'fixture', os: 'linux', shell: 'bash' } }), emit() {} });
ai.audit = () => {};
(async () => {
  await ai.run({ sessionId: 'a', prompt: 'initial task' });
  mode = 'failure';
  await assert.rejects(ai.run({ sessionId: 'a', prompt: 'NEW_TASK' }), /fixture timeout/);
  mode = 'initial';
  await ai.run({ sessionId: 'a', prompt: '继续' });
  assert(JSON.stringify(captured).includes('NEW_TASK'));
  assert(JSON.stringify(captured).includes('fixture timeout'));
  assert.equal(captured.at(-1).content, '继续');
  mode = 'steps'; await ai.run({ sessionId: 'a', prompt: 'TEN_STEP_TASK' });
  mode = 'initial'; await ai.run({ sessionId: 'a', prompt: '继续' });
  assert(JSON.stringify(captured).includes('LATEST_RESULT_10'));
  assert(JSON.stringify(captured).includes('10 步上限'));
  await ai.run({ sessionId: 'b', prompt: 'another session' });
  assert(!JSON.stringify(captured).includes('TEN_STEP_TASK'));
  const pending = retainContext([{role:'user',content:'task'},{role:'assistant',content:'',tool_calls:[{id:'x',function:{name:'execute_command',arguments:'{}'}}]},{role:'assistant',content:'interrupted'}]);
  assert.equal(pending[2].tool_call_id, 'x');
  assert(pending[2].content.includes('unknown'));
  const long = Array.from({length:30}, (_,i)=>[{role:'user',content:'task-'+i},{role:'assistant',content:'x'.repeat(5000)}]).flat();
  const retained = retainContext(long);
  assert(retained[0].content.includes('有损摘录'));
  assert(retained.some(m=>m.content==='task-29'));
  assert(JSON.stringify(retained).length < 75000);
  console.log('PASS: interrupted turn, step limit, latest results, session isolation, unresolved tools and older-context compaction');
})().catch(error => { console.error(error); process.exitCode=1; });
